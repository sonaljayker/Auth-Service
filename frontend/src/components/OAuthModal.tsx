import React, { useState } from 'react'
import { Modal } from '@mantine/core'
import { IconAlertCircle } from '@tabler/icons-react'
import { GoogleIcon, GitHubIcon } from './SocialButtons'
import { TechInput, TechButton } from './TechControls'
import { oauthLoginApi } from '../services/authApi'

export function OAuthModal({
  opened,
  onClose,
  provider,
  onLoginSuccess,
}: {
  opened: boolean
  onClose: () => void
  provider: 'GOOGLE' | 'GITHUB'
  onLoginSuccess?: (res: any) => void
}) {
  const isGoogle = provider === 'GOOGLE'

  const [email, setEmail] = useState('')
  const [name, setName] = useState('')
  const [loading, setLoading] = useState(false)
  const [error, setError] = useState('')

  const handleOAuthSubmit = async (e?: React.FormEvent) => {
    if (e) e.preventDefault()
    setError('')
    if (!email.trim()) {
      setError('Account email is required to authenticate with ' + (isGoogle ? 'Google' : 'GitHub'))
      return
    }

    setLoading(true)
    try {
      const res = await oauthLoginApi({
        provider,
        email: email.trim(),
        name: name.trim() || email.split('@')[0],
        idToken: 'oauth-' + provider.toLowerCase() + '-' + Date.now(),
      })

      if (onLoginSuccess) {
        onLoginSuccess(res)
      }
      onClose()
    } catch (err: any) {
      setError(err.message || 'OAuth identity verification failed')
    } finally {
      setLoading(false)
    }
  }

  return (
    <Modal
      opened={opened}
      onClose={onClose}
      centered
      radius="xs"
      padding="lg"
      title={
        <div style={{ display: 'flex', alignItems: 'center', gap: 10 }}>
          {isGoogle ? <GoogleIcon size={22} /> : <GitHubIcon size={22} />}
          <span style={{ fontWeight: 700, fontSize: '1.05rem', color: '#1A1A1A', fontFamily: 'var(--font-heading)' }}>
            Sign in with {isGoogle ? 'Google Workspace' : 'GitHub Enterprise'}
          </span>
        </div>
      }
      styles={{
        content: {
          backgroundColor: '#FFFFFF',
          border: '1px solid #D7D8D8',
          borderRadius: 4,
        },
        header: {
          borderBottom: '1px solid #D7D8D8',
          paddingBottom: 14,
        },
      }}
    >
      <div style={{ display: 'flex', flexDirection: 'column', gap: 16 }}>
        <p style={{ fontSize: '0.82rem', color: '#85899E', margin: 0, lineHeight: 1.45 }}>
          Authenticate your session using your enterprise {isGoogle ? 'Google' : 'GitHub'} identity.
          A JWT token will be generated by the R&amp;D Platform Auth Service.
        </p>

        {error && (
          <div className="rnd-alert rnd-alert-error" style={{ padding: 10, fontSize: '0.78rem' }}>
            <IconAlertCircle size={16} />
            <span>{error}</span>
          </div>
        )}

        {/* Account Details Form */}
        <form onSubmit={handleOAuthSubmit} style={{ display: 'flex', flexDirection: 'column', gap: 12 }}>
          <TechInput
            id="oauth-email"
            label="WORK OR ACCOUNT EMAIL"
            type="email"
            value={email}
            onChange={(e) => setEmail(e.target.value)}
            placeholder="e.g. engineer@company.com"
            required
          />

          <TechInput
            id="oauth-name"
            label="DISPLAY NAME (OPTIONAL)"
            value={name}
            onChange={(e) => setName(e.target.value)}
            placeholder="e.g. Alex Vance"
          />

          <TechButton type="submit" loading={loading} loadingText="AUTHENTICATING..." style={{ height: 50, marginTop: 4 }}>
            CONFIRM &amp; SIGN IN
          </TechButton>
        </form>
      </div>
    </Modal>
  )
}
